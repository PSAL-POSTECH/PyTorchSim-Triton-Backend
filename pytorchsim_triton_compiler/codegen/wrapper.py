"""Stage `binary` -- the C driver that Spike actually executes.

argv is the tensors' .raw paths in argument order, then the record file's path when the kernel
records runtime attributes, then the scalar parameters' values (all of
them or none: none means the spec's defaults, which is what a gem5 cycle run gets), then an
optional [lo, hi) slice of the flattened grid. A lone "@path" argument names a file holding those words one
a line instead, for a launch whose argv pk's 2048-byte buffer cannot hold."""
import os

from ..contract.kernel_object import (
    CYCLE_CALL_GLOBAL, CYCLE_CALLS, PROGRAM_KEY_SHIFT, RUNTIME_ATTRIBUTE_PROGRAM_ID,
    RUNTIME_ATTRIBUTE_TABLE_HASH, RUNTIME_ATTRIBUTE_WRITE, TOGSIM_VERSION_NUMBER, TRAILING_GRID_PARAMS, grid3,
    parameters, program_key_fits, runtime_scalars)
from ..contract.kernel_spec import is_read, is_written
from ..passes.conversion.pytorchsim_to_llvm import SPAD_POISON_BYTES_SYMBOL, SPAD_POISON_WORD_SYMBOL

C_TYPE = {
    "float64": "double",
    "float32": "float",
    "float16": "_Float16", "bfloat16": "_Float16",
    "int64": "int64_t",
    "int32": "int32_t",
    "int16": "int16_t",
    "int8": "int8_t",
    "uint64": "uint64_t",
    "uint32": "uint32_t",
    "uint16": "uint16_t",
    "uint8": "uint8_t",
    "bool": "int8_t",
}


_FLOAT_CTYPES = ("float", "double", "_Float16")


def _decl_args(spec):
    scalars = runtime_scalars(spec)
    parts = ["int64_t, void*" if kind == "tensor" else scalars[k][1] for kind, k in parameters(spec)]
    parts += ["int32_t"] * len(TRAILING_GRID_PARAMS)
    return ", ".join(parts)


def _call_args(spec):
    scalars = runtime_scalars(spec)
    parts = [f"1, &d_{spec.args[k].name}" if kind == "tensor" else f"s_{scalars[k][0]}"
             for kind, k in parameters(spec)]
    gx, gy, gz = grid3(spec.grid)
    said = {"gridX": str(gx), "gridY": str(gy), "gridZ": str(gz),
            "pidX": "pid_x", "pidY": "pid_y", "pidZ": "pid_z"}
    parts += [said[p] for p in TRAILING_GRID_PARAMS]
    return ", ".join(parts)


def _name_program(subtarget):
    """The dma_index_key that names this program to the model, spelled by the subtarget's target; nothing
    reads it since the model's index dumps are gone."""
    from ..targets import target
    dma = target(subtarget)
    key = _program_key()
    return (f'    __asm__ volatile("{dma.insn(dma.INDEX_KEY, "%0", "x0")}" '
            f': : "r"({key}) : "memory");')


def _poison_decl(subtarget):
    """poison_spad(): every lane's bank, as far as the slots reach, refilled with the lowered module's
    poison word -- .spad's own image reaches lane 0 alone. Strong externs: a module lowered without
    poison does not link with it."""
    return [
        f"extern const int64_t {SPAD_POISON_BYTES_SYMBOL};",
        f"extern const uint64_t {SPAD_POISON_WORD_SYMBOL};",
        "static void poison_spad(void) {",
        f"  for (int64_t lane = 0; lane < {subtarget.vector_lanes}; ++lane) {{",
        f"    volatile uint64_t *p = (volatile uint64_t *)(0x{subtarget.spad_vaddr:x}ULL + "
        f"(uint64_t)lane * {subtarget.spad_size}ULL);",
        f"    for (int64_t i = 0; i < {SPAD_POISON_BYTES_SYMBOL} / 8; ++i) "
        f"p[i] = {SPAD_POISON_WORD_SYMBOL};",
        "  }",
        "}",
    ]


def _program_key():
    return " | ".join(f"(uint64_t)pid_{a} << {s}" for a, s in PROGRAM_KEY_SHIFT.items())


RUNTIME_SOURCE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "runtime_attribute.c")
"""The C runtime a kernel's records are written by, linked with the wrapper when it records any."""


def runtime_flags():
    """What RUNTIME_SOURCE is compiled with: the version its record file's header states."""
    return [f"-DPYTORCHSIM_RUNTIME_ATTRIBUTE_VERSION={TOGSIM_VERSION_NUMBER}u"]


def _record_decl(table):
    return [f"const uint64_t {RUNTIME_ATTRIBUTE_TABLE_HASH} = 0x{table['table_hash']:x}ULL;",
            "void pytorchsim_runtime_attribute_open(const char *path);",
            "extern uint64_t pytorchsim_runtime_attribute_key;",
            f"void {RUNTIME_ATTRIBUTE_WRITE}(uint32_t id, const void *data, uint64_t nbytes);",
            "void pytorchsim_runtime_attribute_close(void);"]


def generate(spec, subtarget, single_program=False, poisoned=False, runtime_attributes=None):
    """The C source for the Spike-side driver: `poisoned` (convert-pytorchsim-to-llvm.poisoned) refills every
    lane's slots before each program; `runtime_attributes` (the attribute table) opens the record file whose
    path follows the tensors', marks each program in it and closes it at the end."""
    gx, gy, gz = grid3(spec.grid)
    if single_program:
        gx = gy = gz = 1
    elif not program_key_fits(spec.grid):
        raise ValueError(
            f"kernel {spec.name}: grid {spec.grid} has a program id past "
            f"{1 << PROGRAM_KEY_SHIFT['y']}, which the dma_index_key field cannot name")
    lines = [
        "/* generated by pytorchsim_triton_compiler/codegen/wrapper.py -- do not edit.",
        "   See the module docstring for the two ABI facts this encodes. */",
        "#include <stdint.h>",
        "#include <stdlib.h>",
        "#include <unistd.h>",
        "#include <fcntl.h>",
        "#include <string.h>",
        "",
        "/* The ranked descriptor an unranked memref argument points at. */",
        "typedef struct {",
        "  void *allocated;",
        "  void *aligned;",
        "  int64_t offset;",
        "  int64_t size;",
        "  int64_t stride;",
        "} pytorchsim_memref_1d;",
    ]
    lines += [
        "",
        f"void {spec.name}({_decl_args(spec)});",
        *(_poison_decl(subtarget) if poisoned else []),
        *([f"int64_t {CYCLE_CALL_GLOBAL};   /* the call each start marker hands gem5 */"]
          if single_program else []),
        *(_record_decl(runtime_attributes) if runtime_attributes else []),
        "",
        "static int load_arg(void *p, size_t n, const char *path) {",
        "  int fd = open(path, O_RDONLY);",
        "  if (fd == -1) return -1;",
        "  if (read(fd, p, n) == -1) { close(fd); return -1; }",
        "  close(fd); return 0;",
        "}",
        "",
        "static int dump_arg(const void *p, size_t n, const char *path) {",
        "  int fd = open(path, O_WRONLY | O_CREAT | O_TRUNC, 0644);",
        "  if (fd == -1) return -1;",
        "  if (write(fd, p, n) == -1) { close(fd); return -1; }",
        "  close(fd); return 0;",
        "}",
        "",
        "/* argv read from the file \"@path\" names, one word a line, after argv[0]; NULL when it cannot be read. */",
        "static char **argv_from_file(const char *path, char *argv0, int *argc) {",
        "  int fd = open(path, O_RDONLY);",
        "  if (fd == -1) return 0;",
        "  off_t n = lseek(fd, 0, SEEK_END);",
        "  char *buf = malloc(n + 1);",
        "  lseek(fd, 0, SEEK_SET);",
        "  for (off_t got = 0, r; got < n; got += r)",
        "    if ((r = read(fd, buf + got, n - got)) <= 0) { close(fd); return 0; }",
        "  close(fd);",
        "  buf[n] = 0;",
        "  int words = 1;",
        "  for (off_t i = 0; i < n; ++i) words += buf[i] == '\\n';",
        "  char **v = malloc((words + 1) * sizeof(char *));",
        "  int k = 0;",
        "  v[k++] = argv0;",
        "  for (char *s = buf, *e; *s; s = e + 1) {",
        "    e = strchr(s, '\\n');",
        "    if (!e) { v[k++] = s; break; }",
        "    *e = 0;",
        "    v[k++] = s;",
        "  }",
        "  v[k] = 0;",
        "  *argc = k;",
        "  return v;",
        "}",
        "",
        "int main(int argc, char *argv[]) {",
        "  if (argc == 2 && argv[1][0] == '@' && !(argv = argv_from_file(argv[1] + 1, argv[0], &argc))) return 2;",
    ]

    for a in spec.args:
        padded = (a.nbytes + 511) & ~511
        c = C_TYPE[a.dtype]
        lines.append(f"  {c}* c_{a.name} = ({c}*)calloc({padded}ULL, 1);")
        lines.append(f"  if (!c_{a.name}) return 1;   /* {padded} bytes */")

    lines.append("")
    for a in spec.args:
        lines.append(f"  pytorchsim_memref_1d d_{a.name} = "
                     f"{{ c_{a.name}, c_{a.name}, 0, {a.numel}, 1 }};")

    lines.append("")
    for i, a in enumerate(spec.args, start=1):
        if is_read(a):
            lines.append(
                f"  if (argc > {i}) load_arg(c_{a.name}, {a.nbytes}ULL, argv[{i}]);")

    nargs = len(spec.args)
    records = bool(runtime_attributes)
    if records:
        nargs += 1
        lines.append(f"  pytorchsim_runtime_attribute_open(argc > {nargs} ? argv[{nargs}] : 0);")
    scalars = runtime_scalars(spec)
    ns = len(scalars)
    if scalars:
        lines.append("")
        lines.append(f"  /* The launch's scalar values follow the {nargs} tensor paths, "
                     f"all {ns} or none; none means the spec's defaults. */")
        for name, ctype, default in scalars:
            lines.append(f"  {ctype} s_{name} = ({ctype}){0 if default is None else default};")
        lines.append(f"  if (argc > {nargs + ns}) {{")
        for i, (name, ctype, _) in enumerate(scalars, start=nargs + 1):
            parse = (f"strtod(argv[{i}], 0)" if ctype in _FLOAT_CTYPES
                     else f"strtoll(argv[{i}], 0, 10)")
            lines.append(f"    s_{name} = ({ctype}){parse};")
        lines.append("  }")
    nargs += ns
    total = gx * gy * gz
    lines += [
        "",
        f"  /* Triton grid {(gx, gy, gz)}"
        + (f", ONE program called {CYCLE_CALLS} times: cycle sampling. */" if single_program else
           f", flattened; argv[{nargs + 1}]/argv[{nargs + 2}] slice it. */"),
        f"  int64_t lo = 0, hi = {total};",
        f"  if (argc > {nargs + 2}) {{",
        f"    lo = atol(argv[{nargs + 1}]);",
        f"    hi = atol(argv[{nargs + 2}]);",
        f"    if (hi > {total}) hi = {total};",
        "  }",
        "  for (int64_t f = lo; f < hi; ++f) {",
        f"    int32_t pid_x = (int32_t)(f % {gx});",
        f"    int32_t pid_y = (int32_t)((f / {gx}) % {gy});",
        f"    int32_t pid_z = (int32_t)(f / {gx * gy});",
        *([] if single_program else [_name_program(subtarget)]),
        *(["    poison_spad();"] if poisoned else []),
        *([f"    pytorchsim_runtime_attribute_key = {_program_key()};",
           f"    {RUNTIME_ATTRIBUTE_WRITE}(0x{RUNTIME_ATTRIBUTE_PROGRAM_ID:x}u, 0, 0);"] if records else []),
        *([f"    for ({CYCLE_CALL_GLOBAL} = 0; {CYCLE_CALL_GLOBAL} < {CYCLE_CALLS}; "
            f"++{CYCLE_CALL_GLOBAL})"] if single_program else []),
        f"    {spec.name}({_call_args(spec)});",
        "  }",
        "",
    ]
    if records:
        lines.append("  pytorchsim_runtime_attribute_close();")

    for i, a in enumerate(spec.args, start=1):
        if is_written(a):
            lines.append(
                f"  if (argc > {i}) dump_arg(c_{a.name}, {a.nbytes}ULL, argv[{i}]);")

    lines += ["  return 0;", "}", ""]
    return "\n".join(lines)


def find_override(kernel_path):
    """Hand-written wrapper next to the kernel file, if present."""
    cand = os.path.splitext(kernel_path)[0] + "_wrapper.c"
    return cand if os.path.exists(cand) else None
