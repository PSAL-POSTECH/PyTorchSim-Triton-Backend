"""Stage `binary` -- the C driver that Spike actually executes."""
import os

from ..contract.kernel_object import TRAILING_GRID_PARAMS, grid3
from ..contract.kernel_spec import is_read, is_written

C_TYPE = {
    "float64": "double",
    "float32": "float",
    "float16": "_Float16", "bfloat16": "_Float16",
    "int64": "int64_t",
    "int32": "int32_t",
    "int16": "int16_t",
    "int8": "int8_t",
    "uint64": "uint64_t",
    "uint32": "uint32_t",
    "uint16": "uint16_t",
    "uint8": "uint8_t",
    "bool": "int8_t",
}


_SIG_CTYPE = {"i32": "int32_t", "i64": "int64_t", "fp32": "float"}


def _scalars(spec):
    """User scalar args, in kernel order, as (name, c_type, value)."""
    out = []
    values = spec.extra.get("scalar_values", {})
    declared = dict(spec.extra.get("scalar_args", []))
    for name, sig in spec.signature.items():
        if sig == "constexpr" or sig.startswith("*"):
            continue
        if name not in values:
            raise ValueError(
                f"kernel {spec.name}: signature declares the runtime scalar "
                f"'{name}: {sig}', so the MLIR function takes it, but "
                f"extra['scalar_values'] gives it no value. Passing nothing "
                f"shifts every argument after it -- add "
                f"extra={{'scalar_values': {{'{name}': ...}}}}")
        ctype = declared.get(name) or _SIG_CTYPE.get(sig)
        if ctype is None:
            raise ValueError(
                f"kernel {spec.name}: no C type known for scalar "
                f"'{name}: {sig}'")
        out.append((name, ctype, values[name]))
    return out


def _decl_args(spec):
    """The kernel's C parameter list: tensors, scalars, the six grid/pid ints.
    """
    parts = []
    for _a in spec.args:
        parts.append("int64_t, void*")
    for _, ctype, _ in _scalars(spec):
        parts.append(ctype)
    parts += ["int32_t"] * len(TRAILING_GRID_PARAMS)
    return ", ".join(parts)


def _call_args(spec):
    """The arguments main() passes, in the order _decl_args declares them.
    """
    parts = []
    for a in spec.args:
        parts.append(f"1, &d_{a.name}")
    for name, ctype, value in _scalars(spec):
        parts.append(f"({ctype}){value}")
    gx, gy, gz = grid3(spec.grid)
    said = {"gridX": str(gx), "gridY": str(gy), "gridZ": str(gz),
            "pidX": "pid_x", "pidY": "pid_y", "pidZ": "pid_z"}
    parts += [said[p] for p in TRAILING_GRID_PARAMS]
    return ", ".join(parts)


def generate(spec, single_program=False):
    """The C source for the Spike-side driver."""
    gx, gy, gz = grid3(spec.grid)
    if single_program:
        gx = gy = gz = 1
    lines = [
        "/* generated by pytorchsim_triton_compiler/elf/emit_wrapper_c.py -- do not edit.",
        "   See the module docstring for the two ABI facts this encodes. */",
        "#include <stdint.h>",
        "#include <stdlib.h>",
        "#include <unistd.h>",
        "#include <fcntl.h>",
        "",
        "/* The ranked descriptor an unranked memref argument points at. */",
        "typedef struct {",
        "  void *allocated;",
        "  void *aligned;",
        "  int64_t offset;",
        "  int64_t size;",
        "  int64_t stride;",
        "} torchsim_memref_1d;",
    ]
    lines += [
        "",
        f"void {spec.name}({_decl_args(spec)});",
        "",
        "static int load_arg(void *p, size_t n, const char *path) {",
        "  int fd = open(path, O_RDONLY);",
        "  if (fd == -1) return -1;",
        "  if (read(fd, p, n) == -1) { close(fd); return -1; }",
        "  close(fd); return 0;",
        "}",
        "",
        "static int dump_arg(const void *p, size_t n, const char *path) {",
        "  int fd = open(path, O_WRONLY | O_CREAT | O_TRUNC, 0644);",
        "  if (fd == -1) return -1;",
        "  if (write(fd, p, n) == -1) { close(fd); return -1; }",
        "  close(fd); return 0;",
        "}",
        "",
        "int main(int argc, char *argv[]) {",
    ]

    for a in spec.args:
        padded = (a.nbytes + 511) & ~511
        c = C_TYPE[a.dtype]
        lines.append(f"  {c}* c_{a.name} = ({c}*)calloc({padded}ULL, 1);")
        lines.append(f"  if (!c_{a.name}) return 1;   /* {padded} bytes */")

    lines.append("")
    for a in spec.args:
        lines.append(f"  torchsim_memref_1d d_{a.name} = "
                     f"{{ c_{a.name}, c_{a.name}, 0, {a.numel}, 1 }};")

    lines.append("")
    for i, a in enumerate(spec.args, start=1):
        if is_read(a):
            lines.append(
                f"  if (argc > {i}) load_arg(c_{a.name}, {a.nbytes}ULL, argv[{i}]);")

    nargs = len(spec.args)
    total = gx * gy * gz
    lines += [
        "",
        f"  /* Triton grid {(gx, gy, gz)}"
        + (", ONE program: cycle sampling. */" if single_program else
           f", flattened; argv[{nargs + 1}]/argv[{nargs + 2}] slice it. */"),
        f"  int64_t lo = 0, hi = {total};",
        f"  if (argc > {nargs + 2}) {{",
        f"    lo = atol(argv[{nargs + 1}]);",
        f"    hi = atol(argv[{nargs + 2}]);",
        f"    if (hi > {total}) hi = {total};",
        "  }",
        "  for (int64_t f = lo; f < hi; ++f) {",
        f"    int32_t pid_x = (int32_t)(f % {gx});",
        f"    int32_t pid_y = (int32_t)((f / {gx}) % {gy});",
        f"    int32_t pid_z = (int32_t)(f / {gx * gy});",
        f"    {spec.name}({_call_args(spec)});",
        "  }",
        "",
    ]

    for i, a in enumerate(spec.args, start=1):
        if is_written(a):
            lines.append(
                f"  if (argc > {i}) dump_arg(c_{a.name}, {a.nbytes}ULL, argv[{i}]);")

    lines += ["  return 0;", "}", ""]
    return "\n".join(lines)


def find_override(kernel_path):
    """Hand-written wrapper next to the kernel file, if present.
    """
    cand = os.path.splitext(kernel_path)[0] + "_wrapper.c"
    return cand if os.path.exists(cand) else None
